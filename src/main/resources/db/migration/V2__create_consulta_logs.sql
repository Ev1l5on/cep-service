CREATE TABLE consulta_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL,
    event_version INTEGER NOT NULL CHECK (event_version > 0),
    cep VARCHAR(8) NOT NULL CHECK (cep ~ '^[0-9]{8}$'),
    consulted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    source VARCHAR(8) NOT NULL CHECK (source IN ('DATABASE', 'VIACEP')),
    response_data JSONB NOT NULL CHECK (jsonb_typeof(response_data) = 'object'),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_consulta_logs_event_id UNIQUE (event_id)
);
